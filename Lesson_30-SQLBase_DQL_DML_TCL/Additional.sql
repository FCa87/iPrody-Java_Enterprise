Принципы ACID — это набор из четырех фундаментальных свойств (Атомарность, Согласованность, Изолированность, Долговечность),
обеспечивающих надежность и целостность данных при выполнении транзакций в системах управления базами данных (СУБД).
Они гарантируют, что транзакции выполняются как единое целое, переходят из одного корректного состояния в другое,
не мешают друг другу и сохраняются навсегда после завершения, даже при сбоях.

Расшифровка принципов ACID:
    A (Atomicity - Атомарность):
    "Либо всё, либо ничего" — вся транзакция должна выполниться целиком, или не выполниться ни одна ее часть. Если происходит сбой, все изменения откатываются.
    C (Consistency - Согласованность):
    Транзакция переводит базу данных из одного допустимого состояния в другое, соблюдая все правила целостности и ограничения (например, баланс счета не может стать отрицательным).
    I (Isolation - Изолированность):
    Параллельные транзакции не должны влиять друг на друга. Результаты одной транзакции не видны другим, пока она не завершится, предотвращая конфликты.
    D (Durability - Долговечность):
    После успешного завершения транзакции (commit) ее результаты сохраняются навсегда и не теряются при последующих системных сбоях или отключении питания. 

Эти принципы являются стандартом для надежных систем, особенно реляционных СУБД, обеспечивая предсказуемое и безопасное управление данными. 



Пример кода, нарушающий принцип атомарности в приложении по переводу денег:

// 1. Списание средств с одного счета
UPDATE accounts SET balance = balance - 100 WHERE user_id = 1;

// !!! Внезапно происходит сбой системы (например, ошибка приложения или отключение света) !!!

// В результате вторая команда не выполняется
// 2. Зачисление средств на другой счет (не выполняется)
UPDATE accounts SET balance = balance + 100 WHERE user_id = 2;

Результат:
В этом примере 100 у.е. исчезли. Первая команда выполнилась, а вторая — нет, что нарушает целостность.
При использовании транзакций (BEGIN ... COMMIT) оба действия либо применились бы, либо откатились.